create index on public.projects (manager_id);
create index on public.payments (project_id);
create index on public.project_rows (project_id);
create index on public.project_rows (group_id);
create index on public.extras (project_id);
create index on public.changes (project_id);
create index on public.items (project_id);
create index on public.items (stage_id);
create index on public.items (assignee_id);
create index on public.items (next_id);
create index on public.issues (project_id);
create index on public.issues (type_id);
create index on public.payouts (person_id);

-- Версія даних: зростає з кожною зміною. За нею сервер бачить, що хтось інший щось змінив.
create table public.app_version (
  id boolean primary key default true check (id),
  version bigint not null default 0
);
insert into public.app_version default values;

-- Усі дані одним знімком --------------------------------------------------------

create function public.load_data() returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'version', (select version from public.app_version),
    'stages', (select coalesce(jsonb_agg(to_jsonb(t) order by t.position), '[]') from public.stages t),
    'issue_types', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.issue_types t),
    'refusal_reasons', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.refusal_reasons t),
    'spec_groups', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.spec_groups t),
    'units', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.units t),
    'makers', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.makers t),
    'works', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.works t),
    'materials', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.materials t),
    'settings', (select to_jsonb(t) from public.settings t),
    'people', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.people t),
    'clients', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.clients t),
    'projects', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.projects t),
    'payments', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.payments t),
    'project_rows', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.project_rows t),
    'extras', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.extras t),
    'changes', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.changes t),
    'items', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.items t),
    'issues', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.issues t),
    'payouts', (select coalesce(jsonb_agg(to_jsonb(t) order by t.seq), '[]') from public.payouts t)
  );
$$;

-- Записує зміни однією транзакцією: або всі, або жодної ----------------------------
-- expected — версія, з якої сервер рахував зміни. Якщо її вже змінив хтось інший, повертає null:
-- сервер перечитує дані й рахує ще раз, тож чужі зміни не затираються.
-- changes — [{ "table": "items", "upsert": [рядки], "delete": ["id", …] }, …].
-- Рядки одного upsert мають однакові поля.

create function public.apply_changes(expected bigint, changes jsonb) returns bigint
language plpgsql set search_path = '' as $$
declare
  current_version bigint;
  change jsonb;
  target text;
  cols text;
  sets text;
begin
  select version into current_version from public.app_version for update;
  if current_version <> expected then
    return null;
  end if;

  for change in select * from jsonb_array_elements(changes) loop
    target := change ->> 'table';
    if target is null or target not in (
      'stages', 'issue_types', 'refusal_reasons', 'spec_groups', 'units', 'makers', 'works', 'materials', 'settings', 'people',
      'clients', 'projects', 'payments', 'project_rows', 'extras', 'changes', 'items', 'issues', 'payouts'
    ) then
      raise exception 'Невідома таблиця: %', target;
    end if;

    if jsonb_array_length(coalesce(change -> 'delete', '[]')) > 0 then
      execute format('delete from public.%I where id in (select jsonb_array_elements_text($1))', target)
        using change -> 'delete';
    end if;

    if jsonb_array_length(coalesce(change -> 'upsert', '[]')) > 0 then
      select string_agg(format('%I', k), ', '), string_agg(format('%I = excluded.%I', k, k), ', ') filter (where k <> 'id')
        into cols, sets
        from jsonb_object_keys(change -> 'upsert' -> 0) as k;
      execute format(
        'insert into public.%I (%s) select %s from jsonb_populate_recordset(null::public.%I, $1) on conflict (id) do %s',
        target, cols, cols, target, case when sets is null then 'nothing' else 'update set ' || sets end
      ) using change -> 'upsert';
    end if;
  end loop;

  -- where обов'язковий: Supabase забороняє update без умови.
  update public.app_version set version = version + 1 where id returning version into current_version;
  return current_version;
end;
$$;

-- Доступ: лише сервер сайту ------------------------------------------------------

do $$
declare
  t text;
begin
  for t in select tablename from pg_catalog.pg_tables where schemaname = 'public' and tablename in (
    'stages', 'issue_types', 'refusal_reasons', 'spec_groups', 'units', 'makers', 'works', 'materials', 'settings', 'people',
    'clients', 'projects', 'payments', 'project_rows', 'extras', 'changes', 'items', 'issues', 'payouts', 'app_version'
  ) loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to service_role', t);
  end loop;
end;
$$;

revoke all on all sequences in schema public from public, anon, authenticated;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.load_data() from public, anon, authenticated;
revoke all on function public.apply_changes(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.load_data() to service_role;
grant execute on function public.apply_changes(bigint, jsonb) to service_role;

commit;
