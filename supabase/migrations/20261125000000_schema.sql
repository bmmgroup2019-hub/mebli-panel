-- Схема бази «Панелі виробництва».
-- Права перевіряє сервер сайту: браузер до бази не звертається. Тому RLS увімкнено без жодного правила,
-- а доступ має лише серверний (секретний) ключ, тобто роль service_role.
-- Виконати один раз у порожньому проекті Supabase: SQL Editor → вставити весь файл → Run.

begin;

-- Довідники -----------------------------------------------------------------

create table public.stages (
  id text primary key,
  position integer not null,
  label text not null,
  hint text not null default '',
  creates_spec boolean not null default false,
  pay jsonb not null default '{"kind":"none"}', -- StagePay: none | percent | works
  constraint stages_pay_kind check (pay ->> 'kind' in ('none', 'percent', 'works'))
);
create unique index stages_label_key on public.stages (lower(label));

create table public.issue_types (
  id text primary key,
  seq bigint generated by default as identity, -- порядок додавання
  name text not null
);
create unique index issue_types_name_key on public.issue_types (lower(name));

-- Причини відмов клієнтів: список веде адміністратор
create table public.refusal_reasons (
  id text primary key,
  seq bigint generated by default as identity,
  name text not null
);
create unique index refusal_reasons_name_key on public.refusal_reasons (lower(name));

create table public.spec_groups (
  id text primary key,
  seq bigint generated by default as identity,
  name text not null
);
create unique index spec_groups_name_key on public.spec_groups (lower(name));

create table public.units (
  id text primary key, -- сама назва одиниці
  seq bigint generated by default as identity
);

create table public.makers (
  id text primary key, -- сама назва виробника
  seq bigint generated by default as identity
);

create table public.works (
  id text primary key,
  seq bigint generated by default as identity,
  name text not null,
  unit text not null,
  stage_id text not null references public.stages deferrable initially deferred,
  price numeric
);
create unique index works_name_key on public.works (lower(name));

create table public.materials (
  id text primary key,
  seq bigint generated by default as identity,
  group_id text not null references public.spec_groups deferrable initially deferred,
  name text not null,
  maker text not null default '',
  unit text not null,
  price numeric,
  work_id text references public.works deferrable initially deferred,
  article text not null
);
create unique index materials_article_key on public.materials (lower(article));

-- Налаштування: фірма й розрахунок вартості (завжди один рядок) ----------------

create table public.settings (
  id text primary key default 'main' check (id = 'main'),
  company jsonb not null,
  margin_percent numeric not null,
  floor_rate numeric,
  floor_stage_id text references public.stages on delete set null deferrable initially deferred
);

-- Люди. Паролі зберігає Supabase Auth, тут їх немає ----------------------------

create table public.people (
  id text primary key,
  seq bigint generated by default as identity,
  auth_user_id uuid unique references auth.users on delete set null,
  name text not null,
  login text not null,
  role text not null check (role in ('admin', 'manager', 'worker', 'buyer')),
  stages text[] not null default '{}', -- етапи людини
  sessions_from timestamptz not null default now() -- сесії дійсні з цього часу: новий пароль завершує старі входи
);
create unique index people_login_key on public.people (lower(login));

-- Замовники й проекти ----------------------------------------------------------

create table public.clients (
  id text primary key,
  seq bigint generated by default as identity,
  name text not null,
  phone text not null default '',
  address text not null default ''
);

create table public.projects (
  id text primary key,
  seq bigint generated by default as identity,
  number text not null unique,
  client_id text not null references public.clients deferrable initially deferred,
  product text not null,
  accepted_on date,
  due_on date,
  client_price numeric,
  manager_id text references public.people on delete set null deferrable initially deferred,
  admin_edited_on date,
  floor integer,
  details jsonb not null default '{}', -- відомості для бланка
  frozen jsonb, -- зафіксовані ціни кошторису (PriceSnapshot)
  refusal jsonb -- відмова клієнта до авансу: { on, reasonId, note, by }; null — проект живий
);

create table public.payments (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text not null references public.projects on delete cascade deferrable initially deferred,
  date date not null,
  amount numeric not null,
  final boolean not null default false
);

create table public.project_rows (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text not null references public.projects on delete cascade deferrable initially deferred,
  list text not null check (list in ('spec', 'estimate')),
  group_id text not null references public.spec_groups deferrable initially deferred,
  name text not null,
  quantity numeric,
  unit text not null,
  note text not null default '',
  purchase text check (purchase in ('ordered', 'bought'))
);

create table public.extras (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text not null references public.projects on delete cascade deferrable initially deferred,
  name text not null,
  amount numeric not null
);

create table public.changes (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text not null references public.projects on delete cascade deferrable initially deferred,
  date date not null,
  author text not null,
  key text not null,
  label text not null,
  "from" text not null,
  "to" text not null
);

-- «Тиждень» і проблеми. Запис посилається на проект; title — лише для вписаного вручну без проекту ---------

create table public.items (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text references public.projects on delete cascade deferrable initially deferred,
  title text not null default '',
  stage_id text not null references public.stages deferrable initially deferred,
  week date not null,
  done_week date,
  done_on date,
  next_id text references public.items on delete set null deferrable initially deferred,
  assignee_id text references public.people on delete set null deferrable initially deferred,
  started_on date,
  admin_marked_on date,
  constraint items_project_or_title check ((project_id is null) <> (title = ''))
);

create table public.issues (
  id text primary key,
  seq bigint generated by default as identity,
  project_id text references public.projects on delete cascade deferrable initially deferred,
  title text not null default '', -- порожньо й без проекту — загальне питання
  type_id text references public.issue_types on delete set null deferrable initially deferred,
  text text not null,
  author text not null,
  created_on date not null,
  resolved boolean not null default false,
  constraint issues_project_or_title check (project_id is null or title = '')
);

-- Виплати зарплати: вносить адміністратор. Людину з виплатами прибрати не можна (restrict),
-- щоб не зникла історія грошей.
create table public.payouts (
  id text primary key,
  seq bigint generated by default as identity,
  person_id text not null references public.people on delete restrict deferrable initially deferred,
  date date not null,
  amount numeric not null check (amount > 0),
  note text not null default ''
);

